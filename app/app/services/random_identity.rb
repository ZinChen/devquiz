# Случайный псевдоним и seed аватара для нового пользователя — в духе
# анонимных имён Google Docs ("Deft Otter"), только на русском.
#
# Списки — по мотивам набора животных, который использует Google Docs для
# анонимных участников (https://www.mentalfloss.com/culture/internet/wild-things-why-google-docs-feature-anonymous-animals),
# переведённого на русский; часть мифических/шуточных персонажей (Кракен,
# Ифрит) сохранена — они часть духа оригинального списка, не только
# зоология. Прилагательные — не только положительные: "Коварный" — не менее
# в характере анонимного псевдонима, чем "Смелый".
#
# Реальные имя и фото из OAuth намеренно не берутся: пользователь может не
# хотеть светить их сразу и сам решает, взять ли их позже (см. профиль).
class RandomIdentity
  ADJECTIVES = %w[
    Быстрый Смелый Тихий Ловкий Хитрый Весёлый Сонный Шустрый Мудрый Дерзкий
    Игривый Спокойный Яркий Задумчивый Отважный Незаметный Проворный Добрый
    Загадочный Бодрый Одинокий Затаившийся Коварный Летучий Ворчливый
    Рассеянный Скользкий Наглый Пугливый Неуловимый Ленивый Взъерошенный
    Голодный Молчаливый Своенравный Упрямый Внимательный Терпеливый Насторожённый
  ].freeze

  ANIMALS = %w[
    Аллигатор Муравьед Броненосец Тур Аксолотль Барсук Мышь Бизон
    Верблюд Капибара Хамелеон Гепард Шиншилла Бурундук Чупакабра Баклан
    Койот Ворон Динго Динозавр Дельфин Утка Слон Хорёк Лис Лягушка Жираф
    Суслик Гризли Ёж Бегемот Гиена Козерог Ифрит Игуана Шакал Джекалоп
    Кенгуру Коала Кракен Лемур Леопард Лигр Лама Ламантин Норка Обезьяна
    Лось Нарвал Орангутан Выдра Панда Пингвин Утконос Питон Квагга Кролик
    Енот Носорог Овца Землеройка Скунс Лори Белка Тигр Черепаха Морж
    Волк Росомаха Вомбат Сова Бобр Кот Тукан
  ].freeze

  # Существительные женского рода — прилагательное перед ними ставится в
  # женском роде ("Хитрая Лиса", не "Хитрый Лиса"). Признак "оканчивается на
  # -а/-я" покрывает почти все случаи автоматически; "Мышь" — исключение,
  # которое под это правило не подпадает, но по роду женское.
  FEMININE_ANIMALS = (ANIMALS.select { |a| a =~ /[ая]$/ } + %w[Мышь]).freeze

  def self.name
    animal = ANIMALS.sample
    adjective = FEMININE_ANIMALS.include?(animal) ? feminize(ADJECTIVES.sample) : ADJECTIVES.sample
    "#{adjective} #{animal}"
  end

  # Короткий id для генерируемого SVG-аватара: не завязан на имя, чтобы смена
  # имени не меняла аватар и наоборот.
  def self.avatar_seed
    SecureRandom.hex(4)
  end

  # Мужская форма на -кий/-гий/-хий/-жий/-чий/-ший/-щий даёт -ая (Тихий →
  # Тихая), остальные на -ий — -яя (Синий → Синяя); нет ни одного случая в
  # ADJECTIVES, поэтому явно не обрабатываем, чтобы не городить лишний код.
  # "-ийся" (причастие вроде "Затаившийся") — отдельно, обычное правило его
  # не покрывает: "ий" там не в конце слова.
  def self.feminize(word)
    return word.sub(/ийся$/, "аяся") if word =~ /[гкхжчшщ]ийся$/
    return word.sub(/ий$/, "ая") if word =~ /[гкхжчшщ]ий$/
    return word.sub(/ый$/, "ая") if word.end_with?("ый")
    return word.sub(/ой$/, "ая") if word.end_with?("ой")
    word
  end
end
